<h2>1. Que sont les cookies</h2>
<p>
    Les cookies sont de petits fichiers texte enregistrés sur votre appareil lorsque vous visitez un site web.
</p>

<h2>2. Quels cookies nous utilisons</h2>

<p><strong>Cookies essentiels</strong></p>
<ul>
    <li>gestion de session (notamment cookie de session Laravel).</li>
    <li>sécurité (notamment jeton CSRF ou XSRF).</li>
    <li>préférence de langue et fonctionnalité de connexion, y compris l’état temporaire pour Se connecter avec Microsoft (via la session).</li>
</ul>

<p>
    Ces cookies sont indispensables au fonctionnement de la plateforme et ne peuvent pas être désactivés sans perturber l’usage normal.
</p>

<h2>3. Absence de cookies de suivi</h2>
<p>
    WinProx n’utilise actuellement pas de cookies de suivi ou de marketing.
</p>

<h2>4. Gérer les cookies</h2>
<p>
    Vous pouvez gérer les cookies via les paramètres de votre navigateur.
</p>

<h2>5. Modifications</h2>
<p>
    La présente politique relative aux cookies peut être modifiée.
</p>
