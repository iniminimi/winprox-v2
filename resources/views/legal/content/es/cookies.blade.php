<h2>1. Qué son las cookies</h2>
<p>
    Las cookies son pequeños archivos de texto que se almacenan en su dispositivo cuando visita un sitio web.
</p>

<h2>2. Qué cookies utilizamos</h2>

<p><strong>Cookies esenciales</strong></p>
<ul>
    <li>gestión de sesión (incluida la cookie de sesión de Laravel).</li>
    <li>seguridad (incluido el token CSRF o XSRF).</li>
    <li>preferencia de idioma y funcionalidad de inicio de sesión.</li>
</ul>

<p>
    Estas cookies son esenciales para el funcionamiento de la plataforma y no pueden desactivarse sin interrumpir el uso normal.
</p>

<h2>3. Sin cookies de seguimiento</h2>
<p>
    WinProx no utiliza actualmente cookies de seguimiento ni de marketing.
</p>

<h2>4. Gestión de cookies</h2>
<p>
    Puede gestionar las cookies a través de la configuración de su navegador.
</p>

<h2>5. Cambios</h2>
<p>
    Esta política de cookies puede actualizarse.
</p>
