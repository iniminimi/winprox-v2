<h2>3. Descripción del servicio</h2>
<p>
    WinProx proporciona una plataforma digital mediante la cual los clientes / administradores pueden:
</p>
<ul>
    <li>registrar incidencias, incluidas a través de portales QR.</li>
    <li>gestionar y dar seguimiento a tareas.</li>
    <li>asignar trabajo a equipos internos y trabajadores.</li>
    <li>registrar y dar seguimiento a mediciones ESG/cumplimiento de forma opcional (si el módulo está activado).</li>
    <li>usar IoT Connect de forma opcional: vincular pasarelas/sensores para que las alarmas y (si aplica) las mediciones inicien el flujo de trabajo en WinProx.</li>
</ul>
<p>
    WinProx es únicamente una plataforma técnica y no realiza trabajos in situ por sí misma.
</p>

<h2>4. Sin ejecución de trabajos</h2>
<p>WinProx:</p>
<ul>
    <li>no realiza trabajos técnicos u operativos in situ.</li>
    <li>no actúa como proveedor de servicios in situ, intermediario ni parte contratante de trabajos operativos.</li>
    <li>no garantiza resultados ni la calidad del trabajo realizado por su organización.</li>
</ul>
<p>
    Todas las decisiones operativas y la ejecución siguen siendo responsabilidad del cliente / administrador y de sus equipos internos.
</p>

