<h2>1. Cosa sono i cookie</h2>
<p>
    I cookie sono piccoli file di testo memorizzati sul suo dispositivo quando visita un sito web.
</p>

<h2>2. Quali cookie utilizziamo</h2>

<p><strong>Cookie essenziali</strong></p>
<ul>
    <li>gestione della sessione (incluso il cookie di sessione Laravel).</li>
    <li>sicurezza (incluso il token CSRF o XSRF).</li>
    <li>preferenza linguistica e funzionalità di accesso.</li>
</ul>

<p>
    Questi cookie sono essenziali per il funzionamento della piattaforma e non possono essere disattivati senza compromettere l'utilizzo normale.
</p>

<h2>3. Nessun cookie di tracciamento</h2>
<p>
    WinProx attualmente non utilizza cookie di tracciamento o di marketing.
</p>

<h2>4. Gestione dei cookie</h2>
<p>
    Può gestire i cookie tramite le impostazioni del browser.
</p>

<h2>5. Modifiche</h2>
<p>
    La presente informativa sui cookie può essere aggiornata.
</p>
