<h2>1. Wat zijn cookies</h2>
<p>
    Cookies zijn kleine tekstbestanden die op je toestel worden opgeslagen wanneer je een website bezoekt.
</p>

<h2>2. Welke cookies gebruiken wij</h2>

<p><strong>Noodzakelijke cookies</strong></p>
<ul>
    <li>sessiebeheer (o.a. Laravel-sessiecookie).</li>
    <li>beveiliging (o.a. CSRF- of XSRF-token).</li>
    <li>taalvoorkeur en aanmeldfunctionaliteit.</li>
</ul>

<p>
    Deze cookies zijn essentieel voor het functioneren van het platform en kunnen niet worden uitgeschakeld zonder het normaal gebruik te verstoren.
</p>

<h2>3. Geen tracking cookies</h2>
<p>
    WinProx gebruikt momenteel geen tracking- of marketingcookies.
</p>

<h2>4. Cookies beheren</h2>
<p>
    Je kan cookies beheren via je browserinstellingen.
</p>

<h2>5. Wijzigingen</h2>
<p>
    Dit cookiebeleid kan worden aangepast.
</p>
