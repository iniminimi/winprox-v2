<p>
    WinProx nutzt externe Dienstleister für Hosting, E-Mail, (sofern aktiviert) Zahlungsabwicklung und (sofern genutzt) Microsoft-Anmeldung.
</p>

<h2>Übersicht</h2>

<table>
