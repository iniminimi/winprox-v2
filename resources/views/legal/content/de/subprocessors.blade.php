        </tr>
    </thead>
    <tbody>
        <tr>
            <td>Cloud86</td>
            <td>Hosting der Plattform (inkl. tägliche Backups)</td>
            <td>EU</td>
        </tr>
        <tr>
            <td>Cloud86-SMTP</td>
            <td>Transaktionale App-E-Mails und Promo-Kampagnen</td>
            <td>EU</td>
        </tr>
