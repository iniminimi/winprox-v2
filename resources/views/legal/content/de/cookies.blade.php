<h2>1. Was sind Cookies</h2>
<p>
    Cookies sind kleine Textdateien, die auf Ihrem Gerät gespeichert werden, wenn Sie eine Website besuchen.
</p>

<h2>2. Welche Cookies wir verwenden</h2>

<p><strong>Erforderliche Cookies</strong></p>
<ul>
    <li>Sitzungsverwaltung (u. a. Laravel-Sitzungscookie).</li>
    <li>Sicherheit (u. a. CSRF- oder XSRF-Token).</li>
    <li>Spracheinstellung und Anmeldefunktion.</li>
</ul>

<p>
    Diese Cookies sind für das Funktionieren der Plattform unerlässlich und können nicht deaktiviert werden, ohne die normale Nutzung zu beeinträchtigen.
</p>

<h2>3. Keine Tracking-Cookies</h2>
<p>
    WinProx verwendet derzeit keine Tracking- oder Marketing-Cookies.
</p>

<h2>4. Cookies verwalten</h2>
<p>
    Sie können Cookies über Ihre Browsereinstellungen verwalten.
</p>

<h2>5. Änderungen</h2>
<p>
    Diese Cookie-Richtlinie kann angepasst werden.
</p>
